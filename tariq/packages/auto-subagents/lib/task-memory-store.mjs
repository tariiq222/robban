/** Private, revision-checked task memory shared by sessions; local writers wait and foreign writers fail without reclaiming locks. */
import { constants } from 'node:fs';
import { mkdir, lstat, realpath, open, rename, unlink, opendir } from 'node:fs/promises';
import path from 'node:path';
import { randomUUID, createHash } from 'node:crypto';
import os from 'node:os';

/** Task data follows explicit Harness home, otherwise the user's private Harness directory. */
export const TASK_MEMORY_DIR = path.join(process.env.DSH_HOME ? path.resolve(process.env.DSH_HOME) : path.join(os.homedir(), '.dsh'), 'auto-task-memory');

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const KINDS = new Set(['progress', 'evidence', 'decision', 'blocker', 'next_step', 'run']);
const MAX_BYTES = 2 * 1024 * 1024;
const WRITERS = Symbol.for('dsh-auto-subagents.task-memory-writers');
const writers = globalThis[WRITERS] ??= new Map();

async function serializeWriter(lock, operation) {
  const previous = writers.get(lock) ?? Promise.resolve();
  const { promise, resolve } = Promise.withResolvers();
  writers.set(lock, promise);
  await previous;
  try { return await operation(); } finally {
    resolve();
    if (writers.get(lock) === promise) writers.delete(lock);
  }
}

const fail = (code, message) => { throw Object.assign(new Error(message), { code: `TASK_MEMORY_${code}` }); };
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
function string(value, name, max) {
  if (typeof value !== 'string' || !value.trim() || value.length > max || /[\x00-\x08\x0b\x0c\x0e-\x1f]/.test(value)) fail('INVALID', `${name} must be nonempty text of at most ${max} characters`);
  return value;
}
function id(value) { if (typeof value !== 'string' || !UUID.test(value)) fail('INVALID', 'taskId must be a UUID generated by task memory'); return value; }
function revision(value) { if (!Number.isSafeInteger(value) || value < 0) fail('INVALID', 'expectedRevision must be a nonnegative safe integer'); }
function refs(value) {
  if (value === undefined) return;
  if (!Array.isArray(value) || value.length > 16) fail('INVALID', 'refs must contain at most 16 literal strings');
  for (const ref of value) string(ref, 'reference', 512);
}
function keys(value, allowed, required = allowed) {
  if (!object(value) || Object.keys(value).some(key => !allowed.includes(key)) || required.some(key => !Object.hasOwn(value, key))) fail('INVALID', 'Task memory contains invalid fields');
}
function timestamp(value) { if (typeof value !== 'string' || !Number.isFinite(Date.parse(value)) || new Date(value).toISOString() !== value) fail('INVALID', 'Task memory timestamp is invalid'); }

/**
 * Persist bounded task records in a dedicated private data directory. Methods return detached JSON records.
 * @param options - Private storage directory and optional record limits (up to 256 entries/64 sessions).
 */
export class TaskMemoryStore {
  constructor({ dir = TASK_MEMORY_DIR, maxEntries = 256, maxSessions = 64 } = {}) {
    if (typeof dir !== 'string' || !path.isAbsolute(dir)) fail('INVALID', 'Task memory dir must be absolute');
    for (const [name, value, max] of [['maxEntries', maxEntries, 256], ['maxSessions', maxSessions, 64]]) {
      if (!Number.isSafeInteger(value) || value < 1 || value > max) fail('INVALID', `${name} must be between 1 and ${max}`);
    }
    this.dir = path.resolve(dir); this.maxEntries = maxEntries; this.maxSessions = maxSessions;
  }
  async repository(repo) {
    string(repo, 'repo', 4096);
    if (!path.isAbsolute(repo)) fail('INVALID', 'repo must be an absolute existing directory');
    const canonical = await realpath(repo);
    if (!(await lstat(canonical)).isDirectory()) fail('INVALID', 'repo must be a directory');
    return canonical;
  }
  namespace(repo) { return path.join(this.dir, createHash('sha256').update(repo).digest('hex')); }
  async directory(repo) {
    const dir = this.namespace(repo);
    // Inspect every component before creating its successor; no configured path may traverse a link.
    let current = path.parse(dir).root;
    for (const component of dir.slice(current.length).split(path.sep).filter(Boolean)) {
      current = path.join(current, component);
      try { await mkdir(current, { mode: 0o700 }); } catch (error) { if (error.code !== 'EEXIST') throw error; }
      const stat = await lstat(current);
      if (stat.isSymbolicLink() || !stat.isDirectory()) fail('UNSAFE', `Unsafe task memory directory: ${current}`);
      if ((current === this.dir || current === dir) && process.platform !== 'win32' && (stat.mode & 0o077)) fail('UNSAFE', 'Task memory directories must be private (0700)');
    }
    const stat = await lstat(dir);
    if (process.platform !== 'win32' && (stat.mode & 0o077)) fail('UNSAFE', 'Task memory directory must be private (0700)');
  }
  filename(taskId, repo) { return path.join(this.namespace(repo), `${id(taskId)}.json`); }
  validate(record) {
    keys(record, ['version', 'taskId', 'repo', 'title', 'goal', 'revision', 'createdAt', 'updatedAt', 'sessions', 'entries']);
    if (record.version !== 1) fail('INVALID', 'Unsupported task memory version');
    id(record.taskId); string(record.repo, 'stored repo', 4096);
    if (!path.isAbsolute(record.repo) || path.resolve(record.repo) !== record.repo) fail('INVALID', 'Stored repo must be canonical absolute path');
    string(record.title, 'title', 200); string(record.goal, 'goal', 4000); revision(record.revision);
    timestamp(record.createdAt); timestamp(record.updatedAt);
    if (!Array.isArray(record.sessions) || !record.sessions.length || record.sessions.length > this.maxSessions || new Set(record.sessions).size !== record.sessions.length) fail('LIMIT', 'Invalid task memory session count');
    for (const session of record.sessions) string(session, 'sessionId', 200);
    if (!Array.isArray(record.entries) || record.entries.length > this.maxEntries || record.revision !== record.entries.length) fail('LIMIT', 'Invalid task memory entry count or revision');
    const ids = new Set();
    for (const entry of record.entries) {
      keys(entry, ['id', 'kind', 'text', 'refs', 'sessionId', 'createdAt'], ['id', 'kind', 'text', 'sessionId', 'createdAt']);
      id(entry.id); if (ids.has(entry.id)) fail('INVALID', 'Duplicate task memory entry id'); ids.add(entry.id);
      if (!KINDS.has(entry.kind)) fail('INVALID', 'Unknown task memory entry kind');
      string(entry.text, 'entry text', 4000); refs(entry.refs); string(entry.sessionId, 'sessionId', 200); timestamp(entry.createdAt);
      if (!record.sessions.includes(entry.sessionId)) fail('INVALID', 'Entry session is missing from task memory sessions');
    }
    return record;
  }
  async read(taskId, repo) {
    const file = this.filename(taskId, repo); let handle;
    try {
      const before = await lstat(file);
      if (before.isSymbolicLink() || !before.isFile()) fail('UNSAFE', 'Task memory files cannot be symbolic links or special files');
      handle = await open(file, constants.O_RDONLY | constants.O_NOFOLLOW);
      const opened = await handle.stat();
      // O_NOFOLLOW admits a fresh regular generation after a cooperating writer's atomic rename.
      if (!constants.O_NOFOLLOW && (opened.ino !== before.ino || opened.dev !== before.dev)) fail('CONFLICT', 'Task memory file changed while opening; retry the read');
      const stat = await handle.stat();
      if (!stat.isFile() || stat.size > MAX_BYTES || (process.platform !== 'win32' && (stat.mode & 0o077))) fail('UNSAFE', 'Task memory file must be private, regular and within the size limit');
      // Bounded read even if another process grows a malformed file after stat.
      const buffer = Buffer.alloc(MAX_BYTES + 1); let size = 0;
      while (size < buffer.length) { const result = await handle.read(buffer, size, buffer.length - size, null); if (!result.bytesRead) break; size += result.bytesRead; }
      if (size > MAX_BYTES) fail('LIMIT', 'Task memory file exceeds the size limit');
      let record;
      try { record = JSON.parse(buffer.subarray(0, size).toString('utf8')); } catch { fail('INVALID', 'Task memory file is not valid JSON'); }
      this.validate(record);
      if (record.taskId !== taskId) fail('INVALID', 'Task memory file id does not match its filename');
      return record;
    } catch (error) {
      if (error.code === 'ENOENT') fail('NOT_FOUND', `Task memory ${taskId} does not exist`);
      if (error.code === 'ELOOP') fail('UNSAFE', 'Task memory files cannot be symbolic links');
      throw error;
    } finally { await handle?.close(); }
  }
  async locked(taskId, repo, operation) {
    await this.directory(repo);
    const lock = path.join(this.namespace(repo), `${id(taskId)}.lock`);
    // Each durable lock has its own local queue, including nested repository admission locks.
    return serializeWriter(lock, async () => {
      let handle;
      try { handle = await open(lock, 'wx', 0o600); } catch (error) { if (error.code === 'EEXIST') fail('BUSY', 'Task memory has an active or unreconciled writer lock; retry or inspect the lock'); throw error; }
      try { return await operation(); } finally { await handle.close(); await unlink(lock); }
    });
  }
  async write(record) {
    this.validate(record);
    const data = JSON.stringify(record) + '\n';
    if (Buffer.byteLength(data) > MAX_BYTES) fail('LIMIT', 'Task memory exceeds the file size limit; start a successor task and reference this task');
    const target = this.filename(record.taskId, record.repo);
    try { const stat = await lstat(target); if (stat.isSymbolicLink() || !stat.isFile()) fail('UNSAFE', 'Task memory target must be a regular file'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const temp = path.join(this.namespace(record.repo), `.${record.taskId}.${randomUUID()}.tmp`); let handle;
    try {
      handle = await open(temp, 'wx', 0o600); await handle.writeFile(data); await handle.sync(); await handle.close(); handle = undefined;
      await rename(temp, target);
      if (process.platform !== 'win32') {
        const directory = await open(this.namespace(record.repo), constants.O_RDONLY); try { await directory.sync(); } finally { await directory.close(); }
      }
    } finally { await handle?.close(); try { await unlink(temp); } catch (error) { if (error.code !== 'ENOENT') throw error; } }
  }
  /** Create a fresh task; a title never selects or merges existing memory. */
  async create({ repo, title, goal, sessionId }) {
    const canonical = await this.repository(repo); string(title, 'title', 200); string(goal, 'goal', 4000); string(sessionId, 'sessionId', 200);
    const taskId = randomUUID(), now = new Date().toISOString();
    const record = { version: 1, taskId, repo: canonical, title, goal, revision: 0, createdAt: now, updatedAt: now, sessions: [sessionId], entries: [] };
    return this.locked(taskId, canonical, async () => { try { await lstat(this.filename(taskId, canonical)); fail('CONFLICT', 'Task memory id already exists'); } catch (error) { if (error.code !== 'ENOENT') throw error; } await this.write(record); return record; });
  }
  /** Read only the explicitly named task belonging to the canonical repository. */
  async get({ repo, taskId }) {
    const canonical = await this.repository(repo); await this.directory(canonical); const record = await this.read(id(taskId), canonical);
    if (record.repo !== canonical) fail('REPO_MISMATCH', 'Task memory belongs to a different repository');
    return record;
  }
  /** List bounded summaries for selection; list never loads another task into the current one. */
  async list({ repo, limit = 10 }) {
    const canonical = await this.repository(repo);
    if (!Number.isSafeInteger(limit) || limit < 1 || limit > 50) fail('INVALID', 'limit must be between 1 and 50');
    await this.directory(canonical); const summaries = [];
    let scanned = 0;
    for await (const item of await opendir(this.namespace(canonical))) {
      if (++scanned > 1000) fail('LIMIT', 'Task memory directory exceeds the 1000-file listing limit; archive completed tasks before listing');
      const name = item.name;
      if (!name.endsWith('.json') || !UUID.test(name.slice(0, -5))) continue;
      const record = await this.read(name.slice(0, -5), canonical);
      if (record.repo !== canonical) continue;
      summaries.push({ taskId: record.taskId, repo: record.repo, title: record.title, revision: record.revision, updatedAt: record.updatedAt, entryCount: record.entries.length, sessionCount: record.sessions.length });
      summaries.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt) || a.taskId.localeCompare(b.taskId)); if (summaries.length > limit) summaries.pop();
    }
    return summaries;
  }
  /** Append one fact with compare-and-swap revision; capacity errors never discard existing facts. */
  async append({ repo, taskId, sessionId, expectedRevision, entry }) {
    id(taskId); string(sessionId, 'sessionId', 200); revision(expectedRevision);
    keys(entry, ['kind', 'text', 'refs'], ['kind', 'text']);
    if (!KINDS.has(entry.kind)) fail('INVALID', 'Unknown task memory entry kind'); string(entry.text, 'entry text', 4000); refs(entry.refs);
    const fact = { kind: entry.kind, text: entry.text, ...(entry.refs === undefined ? {} : { refs: [...entry.refs] }) };
    const canonical = await this.repository(repo);
    return this.locked(taskId, canonical, async () => {
      const record = await this.read(taskId, canonical);
      if (record.repo !== canonical) fail('REPO_MISMATCH', 'Task memory belongs to a different repository');
      if (record.revision !== expectedRevision) fail('CONFLICT', `Task memory revision changed: expected ${expectedRevision}, current ${record.revision}; reload before appending`);
      if (record.entries.length >= this.maxEntries || (!record.sessions.includes(sessionId) && record.sessions.length >= this.maxSessions)) fail('LIMIT', 'Task memory capacity reached; start a successor task and reference this task');
      const now = new Date().toISOString();
      if (!record.sessions.includes(sessionId)) record.sessions.push(sessionId);
      record.entries.push({ id: randomUUID(), ...fact, sessionId, createdAt: now });
      record.revision += 1; record.updatedAt = now; await this.write(record); return record;
    });
  }
}
